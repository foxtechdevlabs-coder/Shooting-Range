#!/usr/bin/env node
/**
 * Compile the Express backend and produce the bundle the desktop app loads.
 *
 * Steps
 *  1. tsc -> backend/server/dist/server/src/*.js (ESM, used by the dev CLI)
 *  2. copy the .sql migrations next to the compiled JS
 *  3. esbuild -> backend/server/dist/server/src/server.bundle.cjs (CommonJS)
 *
 * Why the extra bundle: the Electron main process is CommonJS and the backend
 * is ESM ("type": "module"). A CommonJS file cannot require() an ES module, and
 * Node's ESM loader cannot read files from inside app.asar, so a dynamic
 * import() of the ESM entry fails in the packaged app. Bundling the backend
 * into one CommonJS file removes both problems: the Electron main process
 * simply require()s it, and require() inside app.asar works fine.
 *
 * The two native modules stay external and are loaded from node_modules
 * (shipped unpacked from app.asar via electron-builder's asarUnpack).
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { resolveTsc, root } from './tsc-path.mjs'

// require() accepts plain Windows paths ("C:\...\lib\main.js"); import() only
// accepts file:// URLs, so it must never receive a path.join() result.
const nodeRequire = createRequire(import.meta.url)
const serverDir = path.join(root, 'backend', 'server')
const distDir = path.join(serverDir, 'dist')
const migrationsFrom = path.join(serverDir, 'src', 'db', 'migrations')
const migrationsTo = path.join(distDir, 'server', 'src', 'db', 'migrations')

// Native addons must never be bundled: they are ABI-specific binaries.
const NATIVE_EXTERNALS = ['better-sqlite3', '@node-rs/argon2']

async function loadEsbuild() {
  const candidates = [
    path.join(root, 'node_modules', 'esbuild'),
    path.join(root, 'frontend', 'node_modules', 'esbuild'),
    path.join(root, 'backend', 'node_modules', 'esbuild'),
  ]
  for (const dir of candidates) {
    if (!fs.existsSync(path.join(dir, 'package.json'))) continue
    // esbuild's lib/main.js is CommonJS, and require() takes native paths on
    // every platform. Passing the same path to import() throws
    // ERR_UNSUPPORTED_ESM_URL_SCHEME on Windows ("Received protocol 'c:'").
    const entry = path.join(dir, 'lib', 'main.js')
    if (fs.existsSync(entry)) return nodeRequire(entry)
    // Fall back to the package entry point if esbuild ever moves lib/main.js.
    return nodeRequire(dir)
  }
  // Bare specifier: resolved by Node, no path handling involved.
  try {
    return await import('esbuild')
  } catch {
    console.error('[build:backend] esbuild is not installed. Run "npm install" in the repo root first.')
    process.exit(1)
  }
}

console.log('[build:backend] cleaning', path.relative(root, distDir))
fs.rmSync(distDir, { recursive: true, force: true })

console.log('[build:backend] compiling TypeScript')
execFileSync(process.execPath, [resolveTsc('build:backend'), '-p', 'tsconfig.json'], {
  cwd: serverDir,
  stdio: 'inherit',
})

console.log('[build:backend] copying SQL migrations')
fs.mkdirSync(migrationsTo, { recursive: true })
for (const file of fs.readdirSync(migrationsFrom)) {
  if (file.endsWith('.sql')) fs.copyFileSync(path.join(migrationsFrom, file), path.join(migrationsTo, file))
}

// Tests are compiled too; they are excluded from the installer but keep the build lean.
const testsDir = path.join(distDir, 'server', 'src', 'tests')
if (fs.existsSync(testsDir)) fs.rmSync(testsDir, { recursive: true, force: true })

const entry = path.join(distDir, 'server', 'src', 'index.js')
if (!fs.existsSync(entry)) {
  console.error('[build:backend] FAILED: compiled entry missing at', entry)
  process.exit(1)
}
console.log('[build:backend] ok ->', path.relative(root, entry))

// -- Desktop bundle (CommonJS) -----------------------------------------------
const bundleSource = path.join(distDir, 'server', 'src', 'server.js')
const bundleOut = path.join(distDir, 'server', 'src', 'server.bundle.cjs')

if (!fs.existsSync(bundleSource)) {
  console.error('[build:backend] FAILED: compiled server entry missing at', bundleSource)
  process.exit(1)
}

console.log('[build:backend] bundling backend for the desktop shell')
const esbuild = await loadEsbuild()
const result = await esbuild.build({
  entryPoints: [bundleSource],
  outfile: bundleOut,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  // Native addons and the Electron-provided modules are resolved at runtime.
  external: NATIVE_EXTERNALS,
  define: {
    // The source uses import.meta.url to locate the SQL migrations; under
    // CommonJS we point it at the bundle file so the lookup still works.
    'import.meta.url': '__bundleImportMetaUrl',
  },
  banner: {
    js: [
      '// Generated by scripts/build-backend.mjs - do not edit.',
      'const __bundleImportMetaUrl = require("url").pathToFileURL(__filename).href;',
    ].join('\n'),
  },
  logLevel: 'warning',
  metafile: true,
})

if (!fs.existsSync(bundleOut)) {
  console.error('[build:backend] FAILED: desktop bundle missing at', bundleOut)
  process.exit(1)
}

const sizeMb = (fs.statSync(bundleOut).size / (1024 * 1024)).toFixed(2)
console.log(`[build:backend] ok -> ${path.relative(root, bundleOut)} (${sizeMb} MB)`)

// Sanity check: the bundle must load under plain CommonJS and export startServer.
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
if (pkg.type === 'module') {
  console.warn('[build:backend] WARNING: root package.json has "type": "module"; the Electron main is CommonJS.')
}
